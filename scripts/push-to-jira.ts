/**
 * Load data/seed into a Jira Cloud project, idempotently.
 *
 *   npm run push-to-jira               live when JIRA_* are set (env or apps/api/.env), else a dry run
 *   npm run push-to-jira -- --dry-run  print the plan only
 *
 * Every issue carries a `seed:<id>` label; issues whose label already exists are skipped (found with JQL
 * `labels in ("seed:P001", ...)` in batches). Epics = projects, stories = items, with original estimate,
 * a worklog for time spent, labels per CLAUDE.md §7, and closed projects moved to a Done status.
 * Because Jira can't backdate created/resolved dates, date labels (start:/end:, created:/resolved:) and a
 * complexity label (cx:) are added so a later read reproduces the seed history.
 */
import { join } from 'node:path';
import type { HistoryItem, HistoryProject } from '@scopewise/shared';
import { loadDotEnv } from '../apps/api/src/dotenv';
import { env } from '../apps/api/src/env';
import { JiraClient, adfDoc, discoverCreateMeta, jiraDuration, linkFields, type CreateMeta } from '../apps/api/src/jira';
import { loadSeed } from './demo-common';
import { ROOT, arg } from './lib';

loadDotEnv(join(ROOT, 'apps', 'api', '.env'));

const SEED_BATCH = 50;
const CONCURRENCY = 4;

function epicLabels(p: HistoryProject): string[] {
  return [...new Set([...p.labels, `start:${p.startDate}`, `end:${p.endDate}`, ...(p.status === 'closed' ? ['state:closed'] : [])])];
}

function itemLabels(i: HistoryItem): string[] {
  return [...new Set([...i.labels, `cx:${i.complexity}`, `created:${i.created}`, ...(i.resolved ? [`resolved:${i.resolved}`] : [])])];
}

async function pool<T>(xs: readonly T[], n: number, fn: (x: T) => Promise<void>): Promise<void> {
  let next = 0;
  await Promise.all(
    Array.from({ length: Math.min(n, xs.length) }, async () => {
      while (next < xs.length) {
        const x = xs[next++] as T;
        await fn(x);
      }
    }),
  );
}

async function existingSeedKeys(client: JiraClient, seedIds: string[]): Promise<Map<string, string>> {
  const found = new Map<string, string>();
  const pk = client.cfg.projectKey.replace(/"/g, '');
  for (let i = 0; i < seedIds.length; i += SEED_BATCH) {
    const batch = seedIds.slice(i, i + SEED_BATCH);
    const jql = `project = "${pk}" AND labels in (${batch.map((s) => `"seed:${s}"`).join(', ')})`;
    for (const issue of await client.search(jql, ['labels'])) {
      const seed = (issue.fields.labels ?? []).find((l) => l.startsWith('seed:'))?.slice(5);
      if (seed) found.set(seed, issue.key);
    }
  }
  return found;
}

function printPlan(projects: HistoryProject[], items: HistoryItem[], reason: string) {
  const closed = projects.filter((p) => p.status === 'closed').length;
  const withTime = items.filter((i) => i.timeSpentH > 0).length;
  console.log(`Dry run (${reason}). Nothing was sent to Jira.\n`);
  console.log(`Would create in project ${env.jira()?.projectKey ?? '<JIRA_PROJECT_KEY>'}:`);
  console.log(`  ${projects.length} epics (${closed} closed → transitioned to Done, ${projects.length - closed} open)`);
  console.log(`  ${items.length} stories with original estimates (${items.reduce((s, i) => s + i.originalEstimateH, 0).toFixed(0)}h in total)`);
  console.log(`  ${withTime} worklogs for time spent (${items.reduce((s, i) => s + i.timeSpentH, 0).toFixed(0)}h in total)`);
  console.log('  issues whose seed:<id> label already exists would be skipped\n');
  console.log('First few:');
  for (const p of projects.slice(0, 3)) {
    console.log(`  EPIC  ${p.name}  [${epicLabels(p).join(' ')}]`);
    for (const i of items.filter((x) => x.projectId === p.id).slice(0, 3)) {
      console.log(`    STORY ${i.title}  est ${i.originalEstimateH}h, spent ${i.timeSpentH}h  [${itemLabels(i).join(' ')}]`);
    }
  }
}

async function createProject(client: JiraClient, meta: CreateMeta, p: HistoryProject, existing: Map<string, string>, items: HistoryItem[]) {
  let epicKey = existing.get(p.seedId);
  if (!epicKey) {
    const created = await client.createIssue({
      project: { key: client.cfg.projectKey },
      issuetype: { id: meta.epicTypeId },
      summary: p.name,
      labels: epicLabels(p),
      ...(meta.epicNameFieldId ? { [meta.epicNameFieldId]: p.name.slice(0, 255) } : {}),
      description: adfDoc([[`Fake history generated by scripts/seed.ts for the Scopewise demo (${p.projectType}, size ${p.size}, squad ${p.squad}).`], [`Ran ${p.startDate} to ${p.endDate}.`]]),
    });
    epicKey = created.key;
    console.log(`  + epic ${epicKey} ${p.name}`);
  }
  const todo = items.filter((i) => i.projectId === p.id && !existing.has(i.seedId));
  if (todo.length === 0) return { epic: existing.has(p.seedId) ? 0 : 1, stories: 0, worklogs: 0 };
  const keys = await client.bulkCreate(
    todo.map((i) => ({
      project: { key: client.cfg.projectKey },
      issuetype: { id: meta.storyTypeId },
      summary: i.title,
      ...(meta.labelsOnStory ? { labels: itemLabels(i) } : {}),
      ...(meta.storyHasTimetracking ? { timetracking: { originalEstimate: jiraDuration(i.originalEstimateH) } } : {}),
      ...linkFields(meta, epicKey as string),
      description: adfDoc([[`Fake seed item ${i.seedId}: ${i.category}, complexity ${i.complexity}, role ${i.role}.${i.addedAfterKickoff ? ' Added after kickoff.' : ''}`]]),
    })),
  );
  let worklogs = 0;
  await pool(
    todo.map((i, k) => ({ i, key: keys[k] as string })),
    CONCURRENCY,
    async ({ i, key }) => {
      if (i.timeSpentH > 0) {
        await client.addWorklog(key, i.timeSpentH * 3600, i.resolved ?? i.created);
        worklogs++;
      }
      if (p.status === 'closed') await client.transitionToDone(key).catch(() => false);
    },
  );
  if (p.status === 'closed' && !existing.has(p.seedId)) await client.transitionToDone(epicKey).catch(() => false);
  console.log(`  + ${keys.length} stories under ${epicKey} (${worklogs} worklogs)`);
  return { epic: existing.has(p.seedId) ? 0 : 1, stories: keys.length, worklogs };
}

async function main() {
  const seed = loadSeed();
  const projects = [...seed.projects].sort((a, b) => a.startDate.localeCompare(b.startDate) || a.id.localeCompare(b.id));
  const cfg = env.jira();
  if (arg('dry-run') || !cfg) {
    printPlan(projects, seed.items, cfg ? '--dry-run' : 'JIRA_BASE_URL, JIRA_EMAIL, JIRA_API_TOKEN or JIRA_PROJECT_KEY is not set');
    return;
  }
  const client = new JiraClient(cfg);
  console.log(`Pushing seed history to ${cfg.baseUrl} project ${cfg.projectKey}...`);
  const meta = await discoverCreateMeta(client);
  console.log(`  epic type ${meta.epicTypeId}, story type ${meta.storyTypeName} (${meta.storyTypeId}), link via ${meta.link.kind}${meta.link.kind === 'epic-link' ? ` ${meta.link.fieldId}` : ''}`);
  if (!meta.storyHasTimetracking) console.warn('  warning: time tracking is not on the story create screen; original estimates will be missing');
  if (meta.link.kind === 'none') console.warn('  warning: no parent / Epic Link field; stories will not be linked to epics');
  const existing = await existingSeedKeys(client, [...projects.map((p) => p.seedId), ...seed.items.map((i) => i.seedId)]);
  console.log(`  ${existing.size} seed issues already exist and will be skipped`);
  const totals = { epic: 0, stories: 0, worklogs: 0 };
  for (const p of projects) {
    const r = await createProject(client, meta, p, existing, seed.items);
    totals.epic += r.epic;
    totals.stories += r.stories;
    totals.worklogs += r.worklogs;
  }
  console.log(`Done: ${totals.epic} epics, ${totals.stories} stories, ${totals.worklogs} worklogs created.`);
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? `${err.name}: ${err.message}` : err);
  process.exit(1);
});
